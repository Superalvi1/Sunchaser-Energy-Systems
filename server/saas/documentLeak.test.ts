import test from "node:test";
import assert from "node:assert/strict";
import { mergeBranding } from "../../src/lib/branding.ts";
import { compileDeliveryChallanHtml } from "../../deliveryChallanPdf.ts";
import { compileDeliveryCertificateHtml } from "../../deliveryCertificatePdf.ts";
import { compileWarrantyCertificatePDFHtml } from "../../warrantyCertificatePdf.ts";
import { compileWarrantyHandoverPDFHtml } from "../../warrantyHandoverPdf.ts";
import { builtInContentLibrary, getDefaultBodyHtmlForPageType, mergeContentLibrary, setAuthoringIdentityNeutral } from "../../src/lib/quoteAuthoring.ts";

/** Anything that would identify Sunchaser (or its group companies, accounts or contacts) on another company's document. */
const SUNCHASER = /sunchaser|sunchaserenergy|helios solar|al adam|signals global|lesco|nepra|ceo\.sunchaser|\/assets\/sunchaser/i;

// A company that has set only its name: everything else is missing, which is exactly when a Sunchaser default would leak.
const ACME = mergeBranding({ companyName: "Acme Solar Ltd" }, { neutral: true });
const FOUNDING = mergeBranding({});

const challan: any = {
  id: "c1", challanNumber: "DCH-1", invoiceId: "i1", status: "draft", deliveryTitle: "Delivery 1", deliveryDate: "2026-10-01",
  vehicleNumber: "", driverName: "", installerName: "", receiverName: "Rec", receiverPhone: "", receiverCnic: "", receiverRelation: "",
  items: [{ itemName: "Panel 550W", deliverNowQty: 4, invoiceQty: 4, previouslyDeliveredQty: 0, remainingQtyAfter: 0, serialNumber: "" }],
  photos: [], verificationChecklist: {}, tokenExpiresAt: "2027-01-01T00:00:00Z", verificationToken: "tok",
};
const invoice = { invoiceNumber: "INV-1", customerName: "Cust", customerAddress: "Addr" };
const cert = { documentId: "W-1", issueDate: "2026-10-01", customerName: "Cust", siteAddress: "Addr", projectId: null, deliveryId: null, installationDate: "2026-10-01",
  components: [{ label: "Panels", brand: "X", model: "Y", serial: "S", expiry: "2051-10-01" }] };
const handover = { delivery: { project_title: "P", installation_completed_date: "2026-10-01" }, customer: { name: "Cust" }, system: null, items: [], installed: [], media: [] };

const render = (b: ReturnType<typeof mergeBranding>) => ({
  challan: compileDeliveryChallanHtml({ challan, invoice, branding: b as any, verificationUrl: "https://crm.example.test/delivery/verify/tok" }),
  certificate: compileDeliveryCertificateHtml({ challan, invoice, branding: b as any }),
  warranty: compileWarrantyCertificatePDFHtml(cert as any, b),
  handover: compileWarrantyHandoverPDFHtml(handover as any, b),
});

test("another company's delivery challan, delivery certificate, warranty certificate and handover carry no Sunchaser text, logo or link", () => {
  for (const [name, html] of Object.entries(render(ACME))) {
    assert.doesNotMatch(html, SUNCHASER, `${name} contains Sunchaser identity`);
    assert.match(html, /Acme Solar Ltd/, `${name} shows the company's own name`);
  }
});

test("the QR on the challan is generated locally (no third-party host)", () => {
  const html = render(ACME).challan;
  assert.match(html, /src="data:image\/svg\+xml/);
  assert.doesNotMatch(html, /qrserver|googleapis/);
});

test("a company that has not set a logo gets no logo image at all", () => {
  for (const name of ["warranty", "handover"] as const) assert.doesNotMatch(render(ACME)[name], /<img class="logo"/);
});

test("the founding company's documents are unchanged (Sunchaser defaults still apply to Sunchaser)", () => {
  const f = render(FOUNDING);
  assert.match(f.handover, /Sunchaser warranty policy/);
  assert.match(f.warranty, /sunchaser-logo/);
  assert.match(f.challan, /Generated by Sunchaser CRM/);
});

test("the quote editor offers another company no Sunchaser text, and Sunchaser keeps its own", () => {
  try {
    setAuthoringIdentityNeutral(true);
    const blocks = mergeContentLibrary([]);
    assert.ok(blocks.length >= 6);
    for (const b of blocks) assert.doesNotMatch(b.html, SUNCHASER, `block ${b.id}`);
    for (const t of ["profile", "ceo", "qr", "vision_mission", "warranty"] as const) assert.doesNotMatch(getDefaultBodyHtmlForPageType(t), SUNCHASER, t);
    // the company's own stored blocks still win over the built-ins
    assert.equal(mergeContentLibrary([{ id: "company_profile", name: "Company Profile", html: "<p>Own text</p>" }]).find((b) => b.id === "company_profile")!.html, "<p>Own text</p>");
    setAuthoringIdentityNeutral(false);
    assert.match(builtInContentLibrary().find((b) => b.id === "company_profile")!.html, /Sunchaser/);
  } finally {
    setAuthoringIdentityNeutral(false);
  }
});
