// Journey 5: rename the client in CRM; linked proposals, documents, invoices and portal access keep working.
import fs from "node:fs";
import { STATE, BASE, SHOTS, sql, launch, staffLogin, apiLogin, check, save } from "./lib.mjs";
const ids = JSON.parse(fs.readFileSync(`${STATE}/j6-ids.json`, "utf8"));
const before = { docs: sql(`select count(*) from customer_documents where customer_id='${ids.customerId}'`), quotes: sql(`select count(*) from quotations where lead_id='${ids.leadId}'`) };
const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await staffLogin(page, "t_admin");
await page.getByRole("button", { name: "CRM Database" }).first().click();
const metric = page.getByTestId(`crm-lead-primary-metric-${ids.leadId}`);
await metric.waitFor({ timeout: 20000 });
await metric.click();
const row = metric.locator("xpath=ancestor::*[.//button[normalize-space()='Edit name / contact']][1]");
await row.getByRole("button", { name: "Edit name / contact" }).first().click();
// Controlled inputs expose their value as a property, not an attribute; tag the edit field first.
await page.locator("input").evaluateAll((inputs) => inputs.find((i) => i.value === "Synthetic Invoice Client")?.setAttribute("data-e2e", "edit-name"));
const nameInput = page.locator("[data-e2e=edit-name]");
const form = nameInput.locator("xpath=ancestor::*[.//button[starts-with(normalize-space(),'Save')]][1]");
await nameInput.fill("Synthetic Renamed Client");
await nameInput.scrollIntoViewIfNeeded();
await page.screenshot({ path: `${SHOTS}/j5-00-edit-name.png` });
await form.getByRole("button", { name: /^Save/ }).first().click();
await page.waitForTimeout(2000);
await page.screenshot({ path: `${SHOTS}/j5-01-client-renamed.png` });
check("J5 lead renamed", sql(`select name from leads where id='${ids.leadId}'`) === "Synthetic Renamed Client", sql(`select name from leads where id='${ids.leadId}'`));
check("J5 linked customer renamed with it", sql(`select name from customers where id='${ids.customerId}'`) === "Synthetic Renamed Client");
check("J5 lead keeps its customer link", sql(`select customer_id from leads where id='${ids.leadId}'`) === ids.customerId);
check("J5 invoice still linked to the same customer", sql(`select customer_id from invoices where id='${ids.invoiceId}'`) === ids.customerId);
check("J5 documents and quotations unchanged", sql(`select count(*) from customer_documents where customer_id='${ids.customerId}'`) === before.docs && sql(`select count(*) from quotations where lead_id='${ids.leadId}'`) === before.quotes);
const portalToken = await apiLogin("t_portal_a");
const inv = await fetch(`${BASE}/api/customer-portal/invoices/me`, { headers: { authorization: `Bearer ${portalToken}` } });
check("J5 portal user still sees their invoice", inv.status === 200 && (await inv.text()).includes(ids.invoiceId));
const portal = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await staffLogin(portal, "t_portal_a");
await portal.waitForTimeout(2500);
await portal.screenshot({ path: `${SHOTS}/j5-02-portal-after-rename.png` });
check("J5 portal login works after the rename", (await portal.locator("input[type=password]").count()) === 0);
await browser.close();
save(`${STATE}/j5-results.json`);
