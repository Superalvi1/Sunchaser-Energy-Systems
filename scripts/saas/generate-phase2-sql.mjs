// Generates scripts/saas/phase2-company-foundation.sql from scripts/saas/table-classification.json.
// Run: node scripts/saas/generate-phase2-sql.mjs [--check]   (--check fails if the committed SQL is stale)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const cls = JSON.parse(fs.readFileSync(path.join(here, "table-classification.json"), "utf8")).tables;
const by = (c) => Object.entries(cls).filter(([, v]) => v.class === c).map(([k]) => k).sort();
const lit = (xs) => (xs.length ? "array[" + xs.map((x) => `'${x}'`).join(",") + "]::text[]" : "array[]::text[]");

const sets = {
  tenantNew: [...by("tenant"), ...by("tenant_config")].sort(),
  tenantExisting: by("tenant_existing_company_id"),
  roleTemplate: by("role_template"),
  noAccess: [...by("sunchaser_only"), ...by("dormant"), ...by("identity")].sort(),
};

export function renderUp() {
  return `-- Phase 2: company foundation (additive, idempotent). GENERATED by scripts/saas/generate-phase2-sql.mjs
-- from scripts/saas/table-classification.json. Do not edit by hand; edit the classification and regenerate.
-- Not run in production. Apply only after the read-only preflight passes and a restored backup exists (gate G3).
-- Single transaction: any failure rolls everything back. Existing rows are not rewritten (constant column default).
begin;
set local lock_timeout = '15s';
set local statement_timeout = '20min';

create schema if not exists app;
create table if not exists app.config (key text primary key, value text not null);
insert into app.config (key, value) values ('strict_company', 'off') on conflict (key) do nothing;
create table if not exists app.dropped_policies (
  id bigserial primary key, schema_name text not null, table_name text not null, policy_name text not null,
  permissive text not null, roles text[] not null, cmd text not null, qual text, with_check text,
  dropped_at timestamptz not null default now());
create table if not exists app.original_state (
  kind text not null, name text not null, value text not null, recorded_at timestamptz not null default now(),
  primary key (kind, name));

-- The company a request acts for: the x-company-id header sent by the CRM server on the tenant connection.
create or replace function app.request_company_id() returns text
language plpgsql stable as $f$
declare h text;
begin
  h := nullif(current_setting('request.headers', true), '');
  if h is null then return null; end if;
  return nullif(h::json ->> 'x-company-id', '');
end $f$;

-- Column default. Tenant requests always use the header. Platform/system writes fall back to the founding
-- company only while app.config strict_company = 'off' (single-company compatibility); at go-live set it to 'on'.
create or replace function app.default_company_id() returns text
language plpgsql stable as $f$
declare c text;
begin
  c := app.request_company_id();
  if c is not null then return c; end if;
  if (select value from app.config where key = 'strict_company') = 'on' then return null; end if;
  return 'sunchaser';
end $f$;

create table if not exists public.companies (
  id text primary key check (id ~ '^[a-z][a-z0-9_]{1,40}$'),
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,40}$'),
  name text not null,
  status text not null default 'active' check (status in ('trial','active','suspended','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now());
insert into public.companies (id, slug, name, status) values ('sunchaser', 'sunchaser', 'Sunchaser Energy Systems', 'active')
  on conflict (id) do nothing;

alter table public.users add column if not exists is_platform_admin boolean not null default false;

create table if not exists public.company_memberships (
  id text primary key,
  company_id text not null references public.companies(id),
  user_id text not null references public.users(id) on delete cascade,
  role text not null,
  status text not null default 'active' check (status in ('invited','active','suspended','removed')),
  invited_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, user_id));
create index if not exists company_memberships_user_idx on public.company_memberships (user_id);

-- Staff of the existing business become members of the founding company with their current role.
-- Portal customers (role Customer) are not members: their company comes from their customer record.
insert into public.company_memberships (id, company_id, user_id, role, status)
select 'mem-sunchaser-' || u.id, 'sunchaser', u.id, u.role,
       case u.account_status when 'Approved' then 'active' when 'Suspended' then 'suspended' when 'Pending' then 'invited' else 'removed' end
from public.users u
where u.role <> 'Customer'
on conflict (company_id, user_id) do nothing;

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'crm_tenant') then create role crm_tenant nologin noinherit; end if;
  if exists (select 1 from pg_roles where rolname = 'authenticator') then grant crm_tenant to authenticator; end if;
end $$;
grant usage on schema public to crm_tenant;
grant usage on schema app to crm_tenant;
grant execute on function app.request_company_id(), app.default_company_id() to crm_tenant, service_role;
grant select on app.config to crm_tenant, service_role;
grant select on public.companies to crm_tenant;
alter table public.companies enable row level security;
alter table public.company_memberships enable row level security;
drop policy if exists tenant_sees_own_company on public.companies;
create policy tenant_sees_own_company on public.companies for select to crm_tenant using (id = (select app.request_company_id()));

do $$
declare
  tenant_new text[] := ${lit(sets.tenantNew)};
  tenant_existing text[] := ${lit(sets.tenantExisting)};
  role_template text[] := ${lit(sets.roleTemplate)};
  no_access text[] := ${lit(sets.noAccess)};
  t text; p record; skipped text[] := '{}';
begin
  -- Record the original row-security flag of every table we touch so rollback can restore it.
  foreach t in array tenant_new || tenant_existing || role_template loop
    if to_regclass('public.' || t) is null then skipped := skipped || t; continue; end if;
    insert into app.original_state (kind, name, value)
      select 'relrowsecurity', t, c.relrowsecurity::text from pg_class c where c.oid = ('public.' || t)::regclass
      on conflict do nothing;

    -- Remember what existed before, so rollback only undoes what this migration did.
    if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = t and column_name = 'company_id') then
      insert into app.original_state (kind, name, value) values ('created_column', t, 'company_id') on conflict do nothing;
    else
      insert into app.original_state (kind, name, value)
        select 'column_default', t, coalesce(pg_get_expr(d.adbin, d.adrelid), '')
        from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
        where a.attrelid = ('public.' || t)::regclass and a.attname = 'company_id'
        on conflict do nothing;
    end if;

    if t = any(tenant_new) then
      -- constant default => metadata-only, existing rows keep their timestamps and triggers do not fire
      execute format('alter table public.%I add column if not exists company_id text not null default %L', t, 'sunchaser');
      execute format('alter table public.%I alter column company_id set default app.default_company_id()', t);
    elsif t = any(tenant_existing) then
      execute format('alter table public.%I alter column company_id set default app.default_company_id()', t);
    else
      execute format('alter table public.%I add column if not exists company_id text', t);
      execute format('alter table public.%I alter column company_id set default app.default_company_id()', t);
    end if;

    if not exists (select 1 from pg_constraint where conrelid = ('public.' || t)::regclass and conname = t || '_company_fk') then
      execute format('alter table public.%I add constraint %I foreign key (company_id) references public.companies(id)', t, t || '_company_fk');
      insert into app.original_state (kind, name, value) values ('created_fk', t, t || '_company_fk') on conflict do nothing;
    end if;
    if to_regclass('public.' || t || '_company_idx') is null then
      execute format('create index %I on public.%I (company_id)', t || '_company_idx', t);
      insert into app.original_state (kind, name, value) values ('created_index', t, t || '_company_idx') on conflict do nothing;
    end if;

    -- Legacy policies open to PUBLIC/anon/authenticated (using (true)) would be OR-ed with ours and defeat isolation.
    for p in select * from pg_policies where schemaname = 'public' and tablename = t and policyname not like 'tenant_%'
             and (roles && array['public','anon','authenticated','crm_tenant']::name[]) loop
      insert into app.dropped_policies (schema_name, table_name, policy_name, permissive, roles, cmd, qual, with_check)
        values (p.schemaname, p.tablename, p.policyname, p.permissive, p.roles::text[], p.cmd, p.qual, p.with_check);
      execute format('drop policy %I on public.%I', p.policyname, t);
    end loop;

    execute format('alter table public.%I enable row level security', t);
    if t = any(role_template) then
      -- company_id NULL = system template: readable by every company, writable by none.
      execute format('drop policy if exists tenant_select on public.%I', t);
      execute format('create policy tenant_select on public.%I for select to crm_tenant using (company_id is null or company_id = (select app.request_company_id()))', t);
      execute format('drop policy if exists tenant_insert on public.%I', t);
      execute format('drop policy if exists tenant_update on public.%I', t);
      execute format('drop policy if exists tenant_delete on public.%I', t);
      execute format('create policy tenant_insert on public.%I for insert to crm_tenant with check (company_id = (select app.request_company_id()))', t);
      execute format('create policy tenant_update on public.%I for update to crm_tenant using (company_id = (select app.request_company_id())) with check (company_id = (select app.request_company_id()))', t);
      execute format('create policy tenant_delete on public.%I for delete to crm_tenant using (company_id = (select app.request_company_id()))', t);
    else
      execute format('drop policy if exists tenant_isolation on public.%I', t);
      execute format('create policy tenant_isolation on public.%I for all to crm_tenant using (company_id = (select app.request_company_id())) with check (company_id = (select app.request_company_id()))', t);
    end if;
    execute format('grant select, insert, update, delete on public.%I to crm_tenant', t);
  end loop;

  -- Tables the tenant role must never reach: make sure it holds no privilege on them.
  foreach t in array no_access loop
    if to_regclass('public.' || t) is null then continue; end if;
    execute format('revoke all on public.%I from crm_tenant', t);
  end loop;

  insert into app.original_state (kind, name, value) values ('skipped_missing_tables', 'phase2', array_to_string(skipped, ','))
    on conflict (kind, name) do update set value = excluded.value;
  if array_length(skipped, 1) > 0 then raise notice 'Tables in the classification but absent in this database: %', skipped; end if;
end $$;

grant usage, select on all sequences in schema public to crm_tenant;

-- SECURITY DEFINER / owner-run functions bypass row security. The tenant role must not execute any application
-- function until that function has been reviewed and re-granted explicitly. EXECUTE is granted to PUBLIC by
-- default, so keep service_role working first, then revoke PUBLIC. Extension-owned functions are left alone.
do $$
declare f record;
begin
  for f in select p.oid, p.oid::regprocedure::text as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.prokind in ('f','p')
             and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') loop
    if has_function_privilege('public', f.oid, 'execute') or has_function_privilege('crm_tenant', f.oid, 'execute') then
      insert into app.original_state (kind, name, value) values ('function_public_execute', f.sig, 'granted') on conflict do nothing;
      execute format('grant execute on function %s to service_role', f.sig);
      execute format('revoke execute on function %s from public', f.sig);
      execute format('revoke execute on function %s from crm_tenant', f.sig);
    end if;
  end loop;
end $$;

-- Post-conditions: abort the whole migration if any tenant table is not fully protected.
do $$
declare t text; bad text[] := '{}';
  tenant_all text[] := ${lit([...sets.tenantNew, ...sets.tenantExisting])};
begin
  foreach t in array tenant_all loop
    if to_regclass('public.' || t) is null then continue; end if;
    if not (select c.relrowsecurity from pg_class c where c.oid = ('public.' || t)::regclass) then bad := bad || (t || ':rls-off'); end if;
    if exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname not like 'tenant_%' and roles && array['public','anon','authenticated','crm_tenant']::name[]) then bad := bad || (t || ':open-policy'); end if;
    if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = t and column_name = 'company_id' and is_nullable = 'NO') then bad := bad || (t || ':company_id-nullable'); end if;
  end loop;
  if array_length(bad, 1) > 0 then raise exception 'Phase 2 post-condition failed: %', bad; end if;
end $$;

notify pgrst, 'reload schema';
commit;
`;
}

export function renderDown() {
  return `-- Phase 2 rollback. GENERATED by scripts/saas/generate-phase2-sql.mjs. Safe while only the founding company exists.
-- Copies membership/company data to schema app_rollback_backup first. Restores dropped policies, row-security flags,
-- column defaults and function privileges recorded by the up migration.
begin;
set local lock_timeout = '15s';
create schema if not exists app_rollback_backup;
create table if not exists app_rollback_backup.companies as select * from public.companies;
create table if not exists app_rollback_backup.company_memberships as select * from public.company_memberships;

do $$
declare
  tenant_new text[] := ${lit(sets.tenantNew)};
  tenant_existing text[] := ${lit(sets.tenantExisting)};
  role_template text[] := ${lit(sets.roleTemplate)};
  t text; p record; f record; orig text;
begin
  if (select count(*) from public.companies where id <> 'sunchaser') > 0 then
    raise exception 'Rollback refused: companies other than sunchaser exist. Export or remove their data first.';
  end if;
  foreach t in array tenant_new || tenant_existing || role_template loop
    if to_regclass('public.' || t) is null then continue; end if;
    execute format('drop policy if exists tenant_isolation on public.%I', t);
    execute format('drop policy if exists tenant_select on public.%I', t);
    execute format('drop policy if exists tenant_insert on public.%I', t);
    execute format('drop policy if exists tenant_update on public.%I', t);
    execute format('drop policy if exists tenant_delete on public.%I', t);
    execute format('revoke all on public.%I from crm_tenant', t);
    if exists (select 1 from app.original_state where kind = 'created_fk' and name = t) then
      execute format('alter table public.%I drop constraint if exists %I', t, t || '_company_fk');
    end if;
    if exists (select 1 from app.original_state where kind = 'created_index' and name = t) then
      execute format('drop index if exists public.%I', t || '_company_idx');
    end if;
    if exists (select 1 from app.original_state where kind = 'created_column' and name = t) then
      execute format('alter table public.%I drop column if exists company_id', t);
    else
      select value into orig from app.original_state where kind = 'column_default' and name = t;
      if coalesce(orig, '') = '' then
        execute format('alter table public.%I alter column company_id drop default', t);
      else
        execute format('alter table public.%I alter column company_id set default %s', t, orig);
      end if;
    end if;
    select value into orig from app.original_state where kind = 'relrowsecurity' and name = t;
    if orig = 'false' then execute format('alter table public.%I disable row level security', t); end if;
  end loop;

  for p in select * from app.dropped_policies order by id loop
    if to_regclass(format('%I.%I', p.schema_name, p.table_name)) is null then continue; end if;
    if exists (select 1 from pg_policies where schemaname = p.schema_name and tablename = p.table_name and policyname = p.policy_name) then continue; end if;
    execute format('create policy %I on %I.%I as %s for %s to %s%s%s',
      p.policy_name, p.schema_name, p.table_name, p.permissive, p.cmd,
      (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end);
  end loop;

  for f in select name from app.original_state where kind = 'function_public_execute' loop
    begin
      execute format('grant execute on function %s to public', f.name);
    exception when undefined_function then null; end;
  end loop;
end $$;

drop table if exists public.company_memberships;
alter table public.users drop column if exists is_platform_admin;
drop policy if exists tenant_sees_own_company on public.companies;
drop table if exists public.companies cascade;
revoke all on all sequences in schema public from crm_tenant;
revoke usage on schema public from crm_tenant;
drop schema if exists app cascade;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'crm_tenant') then drop role crm_tenant; end if;
end $$;
notify pgrst, 'reload schema';
commit;
`;
}

const outUp = path.join(here, "phase2-company-foundation.sql");
const outDown = path.join(here, "phase2-company-foundation-rollback.sql");
if (process.argv.includes("--check")) {
  const stale = [];
  if (!fs.existsSync(outUp) || fs.readFileSync(outUp, "utf8") !== renderUp()) stale.push(outUp);
  if (!fs.existsSync(outDown) || fs.readFileSync(outDown, "utf8") !== renderDown()) stale.push(outDown);
  if (stale.length) { console.error("Stale generated SQL:\n" + stale.join("\n") + "\nRun: node scripts/saas/generate-phase2-sql.mjs"); process.exit(1); }
  console.log("Phase 2 SQL is up to date.");
} else {
  fs.writeFileSync(outUp, renderUp());
  fs.writeFileSync(outDown, renderDown());
  console.log("Wrote", path.relative(process.cwd(), outUp), "and", path.relative(process.cwd(), outDown));
}
